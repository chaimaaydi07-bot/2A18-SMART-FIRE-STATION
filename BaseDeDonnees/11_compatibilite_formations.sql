-- Mise à niveau additive du module pour une ancienne base SmartFireStation.
-- Exécuter avec le compte propriétaire des tables, dans SQL Developer (F5).
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
    n NUMBER;
    prochain_id NUMBER;
BEGIN
    SELECT COUNT(*) INTO n FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'SEQ_FORMATION_ID';
    IF n = 0 THEN
        SELECT NVL(MAX(ID), 0) + 1 INTO prochain_id FROM FORMATION;
        EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_FORMATION_ID START WITH ' || prochain_id;
    END IF;

    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'INSCRIRE';
    IF n = 0 THEN
        EXECUTE IMMEDIATE q'~CREATE TABLE INSCRIRE (
            ID_AGENT NUMBER(10) REFERENCES AGENT(ID_AGENT) ON DELETE CASCADE,
            ID NUMBER(10) REFERENCES FORMATION(ID) ON DELETE CASCADE,
            DATE_INSCRIPTION DATE DEFAULT SYSDATE NOT NULL,
            STATUT_INSCRIPTION VARCHAR2(20) DEFAULT 'Inscrit' NOT NULL,
            PRESENCE VARCHAR2(10) CHECK (PRESENCE IN ('Présent', 'Absent')),
            RESULTAT VARCHAR2(20) CHECK (RESULTAT IN ('En cours', 'Réussi', 'Échoué')),
            CONSTRAINT PK_INSCRIRE PRIMARY KEY (ID_AGENT, ID),
            CONSTRAINT CK_INSCRIRE_STATUT CHECK
                (STATUT_INSCRIPTION IN ('Inscrit', 'Confirmé', 'Annulé', 'En attente'))
        )~';
    END IF;

    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'INSCRIPTION' AND COLUMN_NAME = 'ID_FORMATION';
    IF n = 1 THEN
        EXECUTE IMMEDIATE q'~MERGE INTO INSCRIRE i
        USING INSCRIPTION l ON (i.ID = l.ID_FORMATION AND i.ID_AGENT = l.ID_AGENT)
        WHEN NOT MATCHED THEN INSERT
            (ID, ID_AGENT, DATE_INSCRIPTION, STATUT_INSCRIPTION, PRESENCE, RESULTAT)
        VALUES (l.ID_FORMATION, l.ID_AGENT, l.DATE_INSCRIPTION,
                CASE UPPER(l.STATUT_INSCRIPTION)
                    WHEN 'ATTENTE' THEN 'En attente' WHEN 'ANNULE' THEN 'Annulé' ELSE 'Inscrit' END,
                CASE l.PRESENCE WHEN 1 THEN 'Présent' WHEN 0 THEN 'Absent' END,
                CASE UPPER(l.RESULTAT)
                    WHEN 'REUSSI' THEN 'Réussi' WHEN 'ECHEC' THEN 'Échoué' ELSE 'En cours' END)~';
    END IF;
END;
/
COMMIT;

CREATE OR REPLACE TRIGGER TRG_FORMATION_ID
BEFORE INSERT ON FORMATION
FOR EACH ROW
WHEN (NEW.ID IS NULL)
BEGIN
    SELECT SEQ_FORMATION_ID.NEXTVAL INTO :NEW.ID FROM DUAL;
END;
/
