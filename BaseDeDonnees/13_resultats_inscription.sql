-- Huitième table du module Formations. À exécuter après le script 12.
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
    n NUMBER;
BEGIN
    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'RESULTAT_INSCRIPTION';
    IF n = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE RESULTAT_INSCRIPTION (LIBELLE VARCHAR2(20) PRIMARY KEY)';
    END IF;
END;
/

MERGE INTO RESULTAT_INSCRIPTION ref
USING (
    SELECT 'En cours' AS LIBELLE FROM DUAL
    UNION SELECT 'Réussi' FROM DUAL
    UNION SELECT 'Échoué' FROM DUAL
    UNION SELECT RESULTAT FROM INSCRIRE WHERE RESULTAT IS NOT NULL
) valeurs ON (ref.LIBELLE = valeurs.LIBELLE)
WHEN NOT MATCHED THEN INSERT (LIBELLE) VALUES (valeurs.LIBELLE);

COMMIT;

DECLARE
    n NUMBER;
BEGIN
    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS
    WHERE TABLE_NAME = 'INSCRIRE' AND CONSTRAINT_NAME = 'FK_INSCRIRE_RESULTAT_REF';
    IF n = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE INSCRIRE ADD CONSTRAINT FK_INSCRIRE_RESULTAT_REF
            FOREIGN KEY (RESULTAT) REFERENCES RESULTAT_INSCRIPTION(LIBELLE)';
    END IF;
END;
/

SELECT TABLE_NAME FROM USER_TABLES
WHERE TABLE_NAME IN ('AGENT', 'FORMATION', 'INSCRIRE', 'TYPE_FORMATION',
                     'NIVEAU_FORMATION', 'STATUT_FORMATION', 'STATUT_INSCRIPTION',
                     'RESULTAT_INSCRIPTION')
ORDER BY TABLE_NAME;
