-- Module Formations : AGENT, FORMATION, INSCRIRE et quatre tables de référence.
-- Exécuter en mode script dans SQL Developer, avec le compte SMARTFIRE,
-- après le schéma commun et 10_migration_statut_inscription.sql.
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
    n NUMBER;
BEGIN
    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'TYPE_FORMATION';
    IF n = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE TYPE_FORMATION (LIBELLE VARCHAR2(50) PRIMARY KEY)';
    END IF;
    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'NIVEAU_FORMATION';
    IF n = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE NIVEAU_FORMATION (LIBELLE VARCHAR2(30) PRIMARY KEY)';
    END IF;
    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'STATUT_FORMATION';
    IF n = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE STATUT_FORMATION (LIBELLE VARCHAR2(30) PRIMARY KEY)';
    END IF;
    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'STATUT_INSCRIPTION';
    IF n = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE STATUT_INSCRIPTION (LIBELLE VARCHAR2(20) PRIMARY KEY)';
    END IF;
END;
/

MERGE INTO TYPE_FORMATION ref
USING (
    SELECT 'Secourisme' AS LIBELLE FROM DUAL
    UNION SELECT 'Incendie' AS LIBELLE FROM DUAL
    UNION SELECT 'Extincteurs' AS LIBELLE FROM DUAL
    UNION SELECT 'Évacuation' AS LIBELLE FROM DUAL
    UNION SELECT 'Matières dangereuses' AS LIBELLE FROM DUAL
    UNION SELECT 'Sauvetage aquatique' AS LIBELLE FROM DUAL
    UNION SELECT 'Conduite véhicule' AS LIBELLE FROM DUAL
    UNION SELECT DISTINCT TYPE FROM FORMATION WHERE TYPE IS NOT NULL
) valeurs ON (ref.LIBELLE = valeurs.LIBELLE)
WHEN NOT MATCHED THEN INSERT (LIBELLE) VALUES (valeurs.LIBELLE);

MERGE INTO NIVEAU_FORMATION ref
USING (
    SELECT 'Débutant' AS LIBELLE FROM DUAL
    UNION SELECT 'Intermédiaire' AS LIBELLE FROM DUAL
    UNION SELECT 'Avancé' AS LIBELLE FROM DUAL
    UNION SELECT DISTINCT NIVEAU FROM FORMATION WHERE NIVEAU IS NOT NULL
) valeurs ON (ref.LIBELLE = valeurs.LIBELLE)
WHEN NOT MATCHED THEN INSERT (LIBELLE) VALUES (valeurs.LIBELLE);

MERGE INTO STATUT_FORMATION ref
USING (
    SELECT 'Planifiée' AS LIBELLE FROM DUAL
    UNION SELECT 'En cours' AS LIBELLE FROM DUAL
    UNION SELECT 'Terminée' AS LIBELLE FROM DUAL
    UNION SELECT 'Annulée' AS LIBELLE FROM DUAL
    UNION SELECT DISTINCT STATUT FROM FORMATION WHERE STATUT IS NOT NULL
) valeurs ON (ref.LIBELLE = valeurs.LIBELLE)
WHEN NOT MATCHED THEN INSERT (LIBELLE) VALUES (valeurs.LIBELLE);

MERGE INTO STATUT_INSCRIPTION ref
USING (
    SELECT 'Inscrit' AS LIBELLE FROM DUAL
    UNION SELECT 'Confirmé' AS LIBELLE FROM DUAL
    UNION SELECT 'Annulé' AS LIBELLE FROM DUAL
    UNION SELECT 'En attente' AS LIBELLE FROM DUAL
    UNION SELECT DISTINCT STATUT_INSCRIPTION FROM INSCRIRE WHERE STATUT_INSCRIPTION IS NOT NULL
) valeurs ON (ref.LIBELLE = valeurs.LIBELLE)
WHEN NOT MATCHED THEN INSERT (LIBELLE) VALUES (valeurs.LIBELLE);

COMMIT;

DECLARE
    n NUMBER;
BEGIN
    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS
    WHERE CONSTRAINT_NAME = 'FK_FORMATION_TYPE_REF';
    IF n = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE FORMATION ADD CONSTRAINT FK_FORMATION_TYPE_REF
            FOREIGN KEY (TYPE) REFERENCES TYPE_FORMATION(LIBELLE)';
    END IF;
    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS
    WHERE CONSTRAINT_NAME = 'FK_FORMATION_NIVEAU_REF';
    IF n = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE FORMATION ADD CONSTRAINT FK_FORMATION_NIVEAU_REF
            FOREIGN KEY (NIVEAU) REFERENCES NIVEAU_FORMATION(LIBELLE)';
    END IF;
    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS
    WHERE CONSTRAINT_NAME = 'FK_FORMATION_STATUT_REF';
    IF n = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE FORMATION ADD CONSTRAINT FK_FORMATION_STATUT_REF
            FOREIGN KEY (STATUT) REFERENCES STATUT_FORMATION(LIBELLE)';
    END IF;
    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS
    WHERE CONSTRAINT_NAME = 'FK_INSCRIRE_STATUT_REF';
    IF n = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE INSCRIRE ADD CONSTRAINT FK_INSCRIRE_STATUT_REF
            FOREIGN KEY (STATUT_INSCRIPTION) REFERENCES STATUT_INSCRIPTION(LIBELLE)';
    END IF;
END;
/

SELECT TABLE_NAME FROM USER_TABLES
WHERE TABLE_NAME IN ('AGENT', 'FORMATION', 'INSCRIRE', 'TYPE_FORMATION',
                     'NIVEAU_FORMATION', 'STATUT_FORMATION', 'STATUT_INSCRIPTION')
ORDER BY TABLE_NAME;
