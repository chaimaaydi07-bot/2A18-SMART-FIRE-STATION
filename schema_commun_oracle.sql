    IF n=0 THEN
        EXECUTE IMMEDIATE q'~CREATE TABLE INSCRIPTION (
            ID_FORMATION NUMBER NOT NULL,
            ID_AGENT NUMBER NOT NULL,
            DATE_INSCRIPTION DATE DEFAULT SYSDATE NOT NULL,
            STATUT_INSCRIPTION VARCHAR2(20) DEFAULT 'INSCRIT' NOT NULL,
            PRESENCE NUMBER(1),
            RESULTAT VARCHAR2(20) DEFAULT 'EN_ATTENTE' NOT NULL,
            CONSTRAINT PK_INSCRIPTION_AGENT_FORM PRIMARY KEY (ID_FORMATION, ID_AGENT),
            CONSTRAINT FK_INSCR_FORMATION FOREIGN KEY (ID_FORMATION)
                REFERENCES FORMATION(ID) ON DELETE CASCADE,
            CONSTRAINT FK_INSCR_AGENT FOREIGN KEY (ID_AGENT)
                REFERENCES AGENT(ID_AGENT) ON DELETE CASCADE,
            CONSTRAINT CK_INSCR_STATUT CHECK (STATUT_INSCRIPTION IN ('INSCRIT','ATTENTE','ANNULE')),
            CONSTRAINT CK_INSCR_PRESENCE CHECK (PRESENCE IN (0,1) OR PRESENCE IS NULL),
            CONSTRAINT CK_INSCR_RESULTAT CHECK (RESULTAT IN ('EN_ATTENTE','REUSSI','ECHEC'))
        )~';
    END IF;
END;
