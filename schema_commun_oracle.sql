-- Migration douce de l'ancienne table d'association si elle est vide.
DECLARE n NUMBER; c NUMBER; old_table NUMBER;
BEGIN
    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='INSCRIPTION';
    IF n>0 THEN
        SELECT COUNT(*) INTO c FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME='INSCRIPTION' AND COLUMN_NAME='ID_AGENT';
        IF c=0 THEN
            SELECT COUNT(*) INTO n FROM INSCRIPTION;
            SELECT COUNT(*) INTO old_table FROM USER_TABLES WHERE TABLE_NAME='INSCRIPTION_LEGACY';
            IF n>0 THEN
                RAISE_APPLICATION_ERROR(-20001,
                    'INSCRIPTION contient des lignes avec ID_POMPIER : migration manuelle requise.');
            ELSIF old_table>0 THEN
                RAISE_APPLICATION_ERROR(-20002,
                    'INSCRIPTION_LEGACY existe deja; verifiez la migration avant de relancer.');
            ELSE
                EXECUTE IMMEDIATE 'ALTER TABLE INSCRIPTION RENAME TO INSCRIPTION_LEGACY';
            END IF;
        END IF;
    END IF;
END;
