-- Compatibilite avec les anciennes tables FORMATION et contraintes du module.
DECLARE n NUMBER; prochain_id NUMBER;
BEGIN
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='FORMATION' AND COLUMN_NAME='CERTIFICATION';
    IF n=0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE FORMATION ADD (CERTIFICATION NUMBER(1) DEFAULT 0 NOT NULL)';
    END IF;
    UPDATE FORMATION SET CERTIFICATION=0 WHERE CERTIFICATION IS NULL;
    EXECUTE IMMEDIATE 'ALTER TABLE FORMATION MODIFY (CERTIFICATION DEFAULT 0 NOT NULL)';

    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS
     WHERE TABLE_NAME='FORMATION' AND CONSTRAINT_NAME IN ('CK_STATUT','CK_FORMATION_STATUT');
    IF n>0 THEN
        FOR c IN (SELECT CONSTRAINT_NAME FROM USER_CONSTRAINTS
                   WHERE TABLE_NAME='FORMATION' AND CONSTRAINT_NAME IN ('CK_STATUT','CK_FORMATION_STATUT')) LOOP
            EXECUTE IMMEDIATE 'ALTER TABLE FORMATION DROP CONSTRAINT ' || c.CONSTRAINT_NAME;
        END LOOP;
    END IF;

    UPDATE FORMATION SET STATUT = CASE
        WHEN LOWER(STATUT) IN ('planifiée','planifiee') THEN 'planifiee'
        WHEN LOWER(STATUT) IN ('en cours','en_cours') THEN 'en_cours'
        WHEN LOWER(STATUT) IN ('terminée','terminee') THEN 'terminee'
        WHEN LOWER(STATUT) IN ('annulée','annulee') THEN 'annulee'
        ELSE LOWER(STATUT) END;

    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE TABLE_NAME='FORMATION' AND CONSTRAINT_NAME='CK_FORMATION_ID_POS';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE FORMATION ADD CONSTRAINT CK_FORMATION_ID_POS CHECK (ID BETWEEN 1 AND 2147483647)'; END IF;
    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE TABLE_NAME='FORMATION' AND CONSTRAINT_NAME='CK_FORMATION_TITRE_APP';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE FORMATION ADD CONSTRAINT CK_FORMATION_TITRE_APP CHECK (LENGTH(TRIM(TITRE)) BETWEEN 3 AND 100)'; END IF;
    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE TABLE_NAME='FORMATION' AND CONSTRAINT_NAME='CK_FORMATION_TYPE_APP';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE FORMATION ADD CONSTRAINT CK_FORMATION_TYPE_APP CHECK (LENGTH(TRIM(TYPE)) BETWEEN 1 AND 50)'; END IF;
    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE TABLE_NAME='FORMATION' AND CONSTRAINT_NAME='CK_FORMATION_DATES';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE FORMATION ADD CONSTRAINT CK_FORMATION_DATES CHECK (DATE_FIN >= DATE_DEBUT)'; END IF;
    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE TABLE_NAME='FORMATION' AND CONSTRAINT_NAME='CK_FORMATION_DUREE_APP';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE FORMATION ADD CONSTRAINT CK_FORMATION_DUREE_APP CHECK (DUREE BETWEEN 1 AND 99999)'; END IF;
    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE TABLE_NAME='FORMATION' AND CONSTRAINT_NAME='CK_FORMATION_CAPACITE_APP';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE FORMATION ADD CONSTRAINT CK_FORMATION_CAPACITE_APP CHECK (NB_PLACES BETWEEN 1 AND 99999)'; END IF;
    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE TABLE_NAME='FORMATION' AND CONSTRAINT_NAME='CK_FORMATION_CERTIF_APP';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE FORMATION ADD CONSTRAINT CK_FORMATION_CERTIF_APP CHECK (CERTIFICATION IN (0,1))'; END IF;
    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE TABLE_NAME='FORMATION' AND CONSTRAINT_NAME='CK_FORMATION_STATUT_APP';
    IF n=0 THEN EXECUTE IMMEDIATE q'~ALTER TABLE FORMATION ADD CONSTRAINT CK_FORMATION_STATUT_APP CHECK (STATUT IN ('planifiee','en_cours','terminee','annulee'))~'; END IF;

    SELECT COUNT(*) INTO n FROM USER_SEQUENCES WHERE SEQUENCE_NAME='SEQ_FORMATION';
    IF n=0 THEN
        SELECT NVL(MAX(ID),0)+1 INTO prochain_id FROM FORMATION;
        EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_FORMATION START WITH ' || prochain_id || ' INCREMENT BY 1 NOCACHE';
    END IF;
END;
