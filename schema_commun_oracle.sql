-- Migre le nom et les valeurs de statut de la version initiale, sans perdre les lignes.
DECLARE n_etat NUMBER; n_ancien NUMBER; n_contrainte NUMBER;
BEGIN
    SELECT COUNT(*) INTO n_etat FROM USER_TAB_COLUMNS WHERE TABLE_NAME='INSCRIPTION' AND COLUMN_NAME='ETAT';
    SELECT COUNT(*) INTO n_ancien FROM USER_TAB_COLUMNS WHERE TABLE_NAME='INSCRIPTION' AND COLUMN_NAME='STATUT_INSCRIPTION';
    SELECT COUNT(*) INTO n_contrainte FROM USER_CONSTRAINTS WHERE TABLE_NAME='INSCRIPTION' AND CONSTRAINT_NAME='CK_INSCR_STATUT';
    IF n_contrainte>0 THEN EXECUTE IMMEDIATE 'ALTER TABLE INSCRIPTION DROP CONSTRAINT CK_INSCR_STATUT'; END IF;
    IF n_etat=0 AND n_ancien>0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE INSCRIPTION RENAME COLUMN STATUT_INSCRIPTION TO ETAT';
    ELSIF n_etat=0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE INSCRIPTION ADD (ETAT VARCHAR2(20) DEFAULT ''inscrit'' NOT NULL)';
    END IF;
    SELECT COUNT(*) INTO n_contrainte FROM USER_CONSTRAINTS WHERE TABLE_NAME='INSCRIPTION' AND CONSTRAINT_NAME='CK_INSCR_RESULTAT';
    IF n_contrainte>0 THEN EXECUTE IMMEDIATE 'ALTER TABLE INSCRIPTION DROP CONSTRAINT CK_INSCR_RESULTAT'; END IF;
    UPDATE INSCRIPTION SET ETAT = CASE UPPER(ETAT)
        WHEN 'INSCRIT' THEN 'inscrit' WHEN 'ATTENTE' THEN 'attente'
        WHEN 'ANNULE' THEN 'annule' ELSE LOWER(ETAT) END;
    UPDATE INSCRIPTION SET RESULTAT = CASE UPPER(RESULTAT)
        WHEN 'EN_ATTENTE' THEN 'en_attente' WHEN 'REUSSI' THEN 'reussi'
        WHEN 'ECHEC' THEN 'echoue' ELSE LOWER(RESULTAT) END;
    EXECUTE IMMEDIATE 'ALTER TABLE INSCRIPTION MODIFY (ETAT DEFAULT ''inscrit'' NOT NULL)';
    EXECUTE IMMEDIATE 'ALTER TABLE INSCRIPTION MODIFY (RESULTAT DEFAULT ''en_attente'' NOT NULL)';
    SELECT COUNT(*) INTO n_contrainte FROM USER_CONSTRAINTS WHERE TABLE_NAME='INSCRIPTION' AND CONSTRAINT_NAME='CK_INSCR_STATUT';
    IF n_contrainte=0 THEN EXECUTE IMMEDIATE q'~ALTER TABLE INSCRIPTION ADD CONSTRAINT CK_INSCR_STATUT CHECK (ETAT IN ('inscrit','attente','annule'))~'; END IF;
    SELECT COUNT(*) INTO n_contrainte FROM USER_CONSTRAINTS WHERE TABLE_NAME='INSCRIPTION' AND CONSTRAINT_NAME='CK_INSCR_RESULTAT';
    IF n_contrainte=0 THEN EXECUTE IMMEDIATE q'~ALTER TABLE INSCRIPTION ADD CONSTRAINT CK_INSCR_RESULTAT CHECK (RESULTAT IN ('en_attente','reussi','echoue'))~'; END IF;
    SELECT COUNT(*) INTO n_contrainte FROM USER_CONSTRAINTS WHERE TABLE_NAME='INSCRIPTION' AND CONSTRAINT_NAME='CK_INSCRIPTION_IDS_POS';
    IF n_contrainte=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE INSCRIPTION ADD CONSTRAINT CK_INSCRIPTION_IDS_POS CHECK (ID_FORMATION BETWEEN 1 AND 2147483647 AND ID_AGENT BETWEEN 1 AND 2147483647)'; END IF;
END;
