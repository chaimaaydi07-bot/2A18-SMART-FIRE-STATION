DECLARE n NUMBER;
BEGIN
    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='FORMATION';
    IF n=0 THEN
        EXECUTE IMMEDIATE q'~CREATE TABLE FORMATION (
            ID NUMBER(10) PRIMARY KEY,
            TITRE VARCHAR2(100) NOT NULL,
            TYPE VARCHAR2(50) NOT NULL,
            DATE_DEBUT DATE NOT NULL,
            DATE_FIN DATE NOT NULL,
            DUREE NUMBER(5) NOT NULL,
            FORMATEUR VARCHAR2(100),
            LIEU VARCHAR2(100),
