            STATUT VARCHAR2(30) DEFAULT 'planifiee' NOT NULL,
            CONSTRAINT CK_FORMATION_DATES CHECK (DATE_FIN >= DATE_DEBUT),
            CONSTRAINT CK_FORMATION_ID_POS CHECK (ID BETWEEN 1 AND 2147483647),
            CONSTRAINT CK_FORMATION_TITRE_APP CHECK (LENGTH(TRIM(TITRE)) BETWEEN 3 AND 100),
            CONSTRAINT CK_FORMATION_TYPE_APP CHECK (LENGTH(TRIM(TYPE)) BETWEEN 1 AND 50),
            CONSTRAINT CK_FORMATION_DUREE_APP CHECK (DUREE BETWEEN 1 AND 99999),
            CONSTRAINT CK_FORMATION_CAPACITE_APP CHECK (NB_PLACES BETWEEN 1 AND 99999),
            CONSTRAINT CK_FORMATION_CERTIF_APP CHECK (CERTIFICATION IN (0,1)),
